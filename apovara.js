// Αποβάρα: το βάρος (kg) του δοχείου/συσκευασίας κάθε προϊόντος.
//
// Κάθε προϊόν έχει το δικό του πεδίο: ο χρήστης ζυγίζει το προϊόν μαζί με το δοχείο,
// πληκτρολογεί το βάρος της ζυγαριάς και βλέπει το καθαρό βάρος (βάρος − αποβάρο).
//
// Για να προσθέσεις/αλλάξεις προϊόν: άλλαξε τη λίστα παρακάτω (όνομα + αποβάρο σε kg).
const APOVARA_ITEMS = [
    { name: 'Σολομός μπροστά', tare: 0.360 },
    { name: 'Σολομός πίσω', tare: 0.260 },
    { name: 'Μους Αβοκάντο / Dressing', tare: 0.088 },
    { name: 'Pesto (χωρίς καπάκι)', tare: 0.226 },
    { name: 'Κοτόπουλο', tare: 0.500 }
];

// Καθαρό βάρος σε kg (3 δεκαδικά). Επιστρέφει null αν το βάρος δεν είναι έγκυρος
// θετικός αριθμός ή αν είναι μικρότερο από το αποβάρο (αδύνατο αποτέλεσμα).
function netWeight(gross, tare) {
    const g = parseFloat(String(gross).replace(',', '.'));
    if (!isFinite(g) || g <= 0) return null;
    // Ακέραια γραμμάρια για να αποφύγουμε σφάλματα floating point (1.2 - 0.36).
    const netGrams = Math.round(g * 1000) - Math.round(tare * 1000);
    if (netGrams < 0) return null;
    return netGrams / 1000;
}
