// Δουλεύουμε με ΕΥΡΟΣ τιμών, όχι με συγκεκριμένες τιμές: κάθε προμηθευτής έχει ένα
// διάστημα [μικρότερο ποσό, μεγαλύτερο ποσό] από το ιστορικό του. Προτείνεται αν το
// ποσό που πληκτρολογήθηκε πέφτει μέσα σε αυτό το εύρος (με μια μικρή ανοχή γύρω του).
//
// Η ανοχή είναι ποσοστό του ποσού (π.χ. 12%) με ένα ελάχιστο σε ευρώ, ώστε και οι
// προμηθευτές με μία μόνο καταχώρηση να έχουν ένα λογικό εύρος γύρω από την τιμή τους.
const EXPENSE_RANGE_TOLERANCE_PCT = 0.12;  // 12% του ποσού
const EXPENSE_RANGE_TOLERANCE_MIN = 0.5;   // αλλά τουλάχιστον 0.5€

// Αν το ποσό ταιριάζει ΑΚΡΙΒΩΣ με αποθηκευμένο ποσό ΕΝΟΣ ΜΟΝΟ προμηθευτή, επιστρέφει
// το όνομά του ώστε να συμπληρωθεί αυτόματα. Αν το ίδιο ακριβές ποσό υπάρχει σε
// περισσότερους από έναν προμηθευτές (ασάφεια) ή σε κανέναν, επιστρέφει null και
// αφήνουμε τις απλές προτάσεις να δουλέψουν.
function exactExpenseMatch(amount) {
    const target = Math.round(parseFloat(amount) * 100);
    if (!isFinite(target) || target <= 0) return null;

    let match = null;
    for (const name in EXPENSE_HISTORY) {
        const hit = EXPENSE_HISTORY[name].some(v => Math.round(v * 100) === target);
        if (!hit) continue;
        if (match) return null;  // ασάφεια: το ποσό ανήκει σε >1 προμηθευτή
        match = name;
    }
    return match;
}

// Επιστρέφει λίστα προτεινόμενων ονομάτων (Περιγραφών) για το δοσμένο ποσό,
// ταξινομημένα κατά πιθανότητα. Κενή λίστα αν δεν υπάρχει σχετική πρόταση.
function suggestExpenseDescriptions(amount, maxResults = 6) {
    const target = Math.round(parseFloat(amount) * 100) / 100;
    if (!isFinite(target) || target <= 0) return [];

    // Πόσο "παραπάνω" από το εύρος δεχόμαστε, ανάλογα με το ποσό.
    const pad = Math.max(EXPENSE_RANGE_TOLERANCE_MIN, target * EXPENSE_RANGE_TOLERANCE_PCT);

    const candidates = [];

    for (const name in EXPENSE_HISTORY) {
        const values = EXPENSE_HISTORY[name];
        if (!values.length) continue;

        const min = Math.min(...values);
        const max = Math.max(...values);

        // Είναι το ποσό μέσα στο εύρος του προμηθευτή (με την ανοχή);
        if (target < min - pad || target > max + pad) continue;

        // Απόσταση από το διάστημα [min, max]: 0 αν το ποσό είναι μέσα στο εύρος.
        let distToRange = 0;
        if (target < min) distToRange = min - target;
        else if (target > max) distToRange = target - max;

        // Απόσταση από την πιο κοντινή πραγματική καταχώρηση (για ισοπαλίες).
        let distToNearest = Infinity;
        for (const v of values) {
            const d = Math.abs(v - target);
            if (d < distToNearest) distToNearest = d;
        }

        candidates.push({ name, distToRange, distToNearest, freq: values.length });
    }

    // Κατάταξη:
    //  1) όσοι έχουν πραγματική τιμή πιο κοντά στο ποσό πρώτοι (π.χ. ο Ντόντης που
    //     έχει καταχωρηθεί ακριβώς με 24 βγαίνει για το 24),
    //  2) μετά όσοι έχουν το ποσό μέσα στο εύρος τους (distToRange μικρότερο),
    //  3) τέλος οι πιο συχνοί προμηθευτές.
    candidates.sort((a, b) =>
        a.distToNearest - b.distToNearest ||
        a.distToRange - b.distToRange ||
        b.freq - a.freq
    );

    return candidates.slice(0, maxResults).map(r => r.name);
}
